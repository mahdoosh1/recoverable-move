pub fn sentinel_for(sector_size: usize) -> Vec<u8> {
    let mut buf = Vec::with_capacity(sector_size);
    while buf.len() < sector_size {
        let take = (sector_size - buf.len()).min(SENTINEL.len());
        buf.extend_from_slice(&SENTINEL[..take]);
    }
    buf
}